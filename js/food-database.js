    /**
     * Get combined database (Default items + Custom user items)
     */
    getAllFoods() {
        const customFoods = (typeof StorageManager !== 'undefined') ? StorageManager.getCustomFoods() : [];
        return [...this.ITEMS, ...customFoods];
    },

    /**
     * Find item by ID
     */
    getFoodById(id) {
        return this.getAllFoods().find(item => item.id === id);
    },

    /**
     * Search foods by keyword and category
     */
    searchFoods(query = '', category = 'All') {
        let items = this.getAllFoods();
        if (category && category !== 'All') {
            items = items.filter(f => f.category === category);
        }
        if (query && query.trim()) {
            const q = query.trim().toLowerCase();
            items = items.filter(f => 
                f.name.toLowerCase().includes(q) || 
                (f.category && f.category.toLowerCase().includes(q))
            );
        }
        return items;
    },

    /**
     * Calculate nutrients proportionally based on food item, quantity and unit
     */
    calculateNutrients(foodItem, quantity, unit) {
        if (!foodItem || quantity <= 0) return null;

        // Determine effective grams consumed
        let grams = quantity;
        if (unit !== 'g' && unit !== 'ml') {
            if (foodItem.unitWeights && foodItem.unitWeights[unit]) {
                grams = quantity * foodItem.unitWeights[unit];
            } else if (foodItem.servingWeightG) {
                grams = quantity * foodItem.servingWeightG;
            }
        }

        const ratio = grams / 100;

        return {
            grams: Utils.round(grams, 1),
            calories: Math.round(foodItem.calories * ratio),
            protein: Utils.round(foodItem.protein * ratio, 1),
            carbs: Utils.round(foodItem.carbs * ratio, 1),
            fat: Utils.round(foodItem.fat * ratio, 1),
            fibre: Utils.round((foodItem.fibre || 0) * ratio, 1),
            sugar: Utils.round((foodItem.sugar || 0) * ratio, 1),
            satFat: Utils.round((foodItem.satFat || 0) * ratio, 1),
            sodium: Math.round((foodItem.sodium || 0) * ratio),
            // Vitamins
            vitA: Math.round((foodItem.vitA || 0) * ratio),
            vitB: foodItem.vitB || 'Data unavailable',
            vitC: Utils.round((foodItem.vitC || 0) * ratio, 1),
            vitD: Math.round((foodItem.vitD || 0) * ratio),
            vitE: Utils.round((foodItem.vitE || 0) * ratio, 1),
            vitK: Utils.round((foodItem.vitK || 0) * ratio, 1),
            // Minerals
            calcium: Math.round((foodItem.calcium || 0) * ratio),
            iron: Utils.round((foodItem.iron || 0) * ratio, 1),
            magnesium: Math.round((foodItem.magnesium || 0) * ratio),
            potassium: Math.round((foodItem.potassium || 0) * ratio),
            zinc: Utils.round((foodItem.zinc || 0) * ratio, 1)
        };
    }
